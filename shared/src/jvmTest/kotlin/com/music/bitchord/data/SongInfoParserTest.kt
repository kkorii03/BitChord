package com.music.bitchord.data

import kotlinx.serialization.json.Json
import kotlinx.serialization.json.jsonObject
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertFailsWith
import kotlin.test.assertNull

class SongInfoParserTest {
    private fun page(data: String = "{}", id: String = "abcdefghijk", views: String = "12345") = """
        <script>var ytInitialPlayerResponse = {"videoDetails":{"videoId":"$id","viewCount":"$views","title":"A } title"},
        "microformat":{"playerMicroformatRenderer":{"uploadDate":"2024-02-03"}}}; window.after = true;</script>
        <script>var ytInitialData = $data;</script>
    """.trimIndent()

    @Test fun extractsCountsWithoutTreatingUploadDateAsReleaseYear() {
        val info = SongInfoParser.parse(page("""{"contents":{"videoPrimaryInfoRenderer":{
            "buttons":[{"toggleButtonRenderer":{"defaultIcon":{"iconType":"LIKE"},"defaultText":{"simpleText":"1.2K"}}}]},
            "commentsEntryPointHeaderRenderer":{"commentCount":{"simpleText":"42"}}}}"""), "abcdefghijk")
        assertEquals("12345", info.views)
        assertEquals("1.2K", info.likes)
        assertEquals("42", info.comments)
        assertNull(info.releaseDate)
        assertNull(info.releaseYear)
    }

    @Test fun usesExplicitReleaseDateInsteadOfVideoUploadDate() {
        val html = page().replace("\"title\":\"A } title\"",
            "\"title\":\"A } title\",\"shortDescription\":\"Provided to YouTube\\nReleased on: 1987-07-27\\nAuto-generated by YouTube.\"")
        assertEquals("1987-07-27", SongInfoParser.parse(html, "abcdefghijk").releaseDate)
        assertNull(SongInfoParser.parse(html.replace("1987-07-27", "1987-02-30"), "abcdefghijk").releaseDate)
    }

    @Test fun ignoresRecommendedVideoLikesAndMissingCounts() {
        val info = SongInfoParser.parse(page("""{"recommendations":{"toggleButtonRenderer":{
            "defaultIcon":{"iconType":"LIKE"},"defaultText":{"simpleText":"999"}}}}""", views = "-1"), "abcdefghijk")
        assertNull(info.likes)
        assertNull(info.comments)
        assertNull(info.views)
    }

    @Test fun supportsCurrentLikeButtonAndZeroCounts() {
        val info = SongInfoParser.parse(page("""{"videoPrimaryInfoRenderer":{"likeButtonViewModel":{
            "toggleButtonViewModel":{"defaultButtonViewModel":{"buttonViewModel":{"title":"0"}}}}}}""", views = "0"), "abcdefghijk")
        assertEquals("0", info.likes)
        assertEquals("0", info.views)
    }

    @Test fun rejectsWrongIdentityAndConsentPages() {
        assertFailsWith<IllegalStateException> { SongInfoParser.parse(page(id = "other_song_"), "abcdefghijk") }
        assertFailsWith<IllegalStateException> { SongInfoParser.parse("<html>Consent</html>", "abcdefghijk") }
    }

    @Test fun readsCommentPanelCountWhenHeaderHasOnlyLabel() {
        val info = SongInfoParser.parse(page("""{
            "commentsHeaderRenderer":{"countText":{"runs":[{"text":"Comments"}]}},
            "engagementPanels":[{"engagementPanelSectionListRenderer":{
                "targetId":"engagement-panel-comments-section",
                "header":{"engagementPanelTitleHeaderRenderer":{"contextualInfo":{"runs":[{"text":"2.4M"}]}}}
            }}]}"""), "abcdefghijk")
        assertEquals("2.4M", info.comments)
    }

    @Test fun readsReleaseFactsAndCreditsFromTheDescription() {
        val html = page().replace(
            "\"title\":\"A } title\"",
            "\"title\":\"A } title\",\"shortDescription\":\"Provided to YouTube\\n" +
                "Released on: 1987-07-27\\nGenre: Pop\\nComposer: A, B\\nLyricist: C\\n" +
                "Auto-generated by YouTube.\"",
        )
        val info = SongInfoParser.parse(html, "abcdefghijk")
        assertEquals("1987-07-27", info.releaseDate)
        assertEquals("Pop", info.genre)
        assertEquals("A, B", info.composer)
        assertEquals("C", info.lyricist)
    }

    @Test fun readsWatchDataWithoutAPlayerResponse() {
        val data = Json.parseToJsonElement(
            """
            {
              "contents": {
                "videoPrimaryInfoRenderer": {
                  "viewCount": {"videoViewCountRenderer": {"viewCount": {"simpleText": "1,234,567 views"}}},
                  "buttons": [{"toggleButtonRenderer": {
                    "defaultIcon": {"iconType": "LIKE"},
                    "defaultText": {"simpleText": "1.2K"}
                  }}]
                },
                "commentsEntryPointHeaderRenderer": {"commentCount": {"simpleText": "42"}}
              }
            }
            """.trimIndent(),
        ).jsonObject
        val info = SongInfoParser.parseWatch(null, data, "abcdefghijk")
        assertEquals("1234567", info.views)
        assertEquals("1.2K", info.likes)
        assertEquals("42", info.comments)
        assertEquals(false, info.failed)
    }

    @Test fun keepsKoreanAbbreviatedCountsInsteadOfStrippingTheUnit() {
        val data = Json.parseToJsonElement(
            """
            {
              "contents": {
                "videoPrimaryInfoRenderer": {
                  "viewCount": {"videoViewCountRenderer": {"viewCount": {"simpleText": "조회수 1.2만회"}}},
                  "buttons": [{"segmentedLikeDislikeButtonViewModel": {"likeButtonViewModel": {
                    "likeButtonViewModel": {"toggleButtonViewModel": {"toggleButtonViewModel": {
                      "defaultButtonViewModel": {"buttonViewModel": {"title": "1949만"}}
                    }}}
                  }}}]
                },
                "commentsEntryPointHeaderRenderer": {"commentCount": {"simpleText": "댓글 246만개"}}
              }
            }
            """.trimIndent(),
        ).jsonObject
        val info = SongInfoParser.parseWatch(null, data, "abcdefghijk")
        assertEquals("1.2만", info.views)
        assertEquals("1949만", info.likes)
        assertEquals("246만", info.comments)
    }

    @Test fun prefersTheExactViewCountNextToAnAbbreviatedOne() {
        val data = Json.parseToJsonElement(
            """
            {"contents": {"videoPrimaryInfoRenderer": {"viewCount": {"videoViewCountRenderer": {
              "viewCount": {"simpleText": "조회수 5980만회"},
              "originalViewCount": "59809305"
            }}}}}
            """.trimIndent(),
        ).jsonObject
        assertEquals("59809305", SongInfoParser.parseWatch(null, data, "abcdefghijk").views)
    }

    @Test fun ignoresAZeroOriginalViewCountSentinel() {
        val data = Json.parseToJsonElement(
            """
            {"contents": {"videoPrimaryInfoRenderer": {"viewCount": {"videoViewCountRenderer": {
              "viewCount": {"simpleText": "조회수 152,829,818회"},
              "originalViewCount": "0"
            }}}}}
            """.trimIndent(),
        ).jsonObject
        assertEquals("152829818", SongInfoParser.parseWatch(null, data, "abcdefghijk").views)
    }

    @Test fun readsTheCombinedComposerLyricistCreditFromAutoGeneratedDescriptions() {
        val data = Json.parseToJsonElement(
            """
            {"videoSecondaryInfoRenderer": {"attributedDescription": {"content":
              "Provided to YouTube by Example\n\nReleased on: 2017-06-23\nComposer  Lyricist: Thom Yorke\n"
            }}}
            """.trimIndent(),
        ).jsonObject
        val info = SongInfoParser.parseWatch(null, data, "abcdefghijk")
        assertEquals("2017-06-23", info.releaseDate)
        assertNull(info.composer)
        assertEquals("Thom Yorke", info.lyricist)
    }

    @Test fun readsKoreanDescriptionLabelsWithoutAPlayerResponse() {
        val data = Json.parseToJsonElement(
            """
            {"videoSecondaryInfoRenderer": {"description": {"runs": [{"text":
              "Provided to YouTube by Example\n\n발매일: 2010-12-09\n장르: 발라드\n작곡: A, B\n작사: C\n"
            }]}}}
            """.trimIndent(),
        ).jsonObject
        val info = SongInfoParser.parseWatch(null, data, "abcdefghijk")
        assertEquals("2010-12-09", info.releaseDate)
        assertEquals("발라드", info.genre)
        assertEquals("A, B", info.composer)
        assertEquals("C", info.lyricist)
    }

    @Test fun readsKoreanWatchDataWhenThePlayerIsBotGated() {
        val player = Json.parseToJsonElement(
            """{"playabilityStatus":{"status":"LOGIN_REQUIRED","reason":"로그인하여 봇이 아님을 확인하세요."}}""",
        ).jsonObject
        val data = Json.parseToJsonElement(
            """
            {
              "contents": {"videoPrimaryInfoRenderer": {
                "viewCount": {"videoViewCountRenderer": {"viewCount": {"simpleText": "조회수 59,809,305회"}}}
              }},
              "videoSecondaryInfoRenderer": {"attributedDescription": {"content":
                "Provided to YouTube by Example\n\nReleased on: 2010-12-09\nAuto-generated by YouTube."
              }}
            }
            """.trimIndent(),
        ).jsonObject
        val info = SongInfoParser.parseWatch(player, data, "abcdefghijk")
        assertEquals(false, info.failed)
        assertEquals("59809305", info.views)
        assertEquals("2010-12-09", info.releaseDate)
    }

    @Test fun readsTheYearFromKoreanAndEnglishAlbumSubtitles() {
        assertEquals("2010", releaseYearFromSubtitle("앨범 • 2010년"))
        assertEquals("2010", releaseYearFromSubtitle("Album • 2010"))
        assertEquals("2010", releaseYearFromSubtitle("아이유 • 앨범 • 2010년"))
        assertNull(releaseYearFromSubtitle("앨범 • 7곡"))
        assertNull(releaseYearFromSubtitle("앨범 • 2010 Remaster"))
    }

    @Test fun compactsRawCounts() {
        val sep = java.text.DecimalFormatSymbols.getInstance().decimalSeparator
        assertEquals("0", compactCount("0"))
        assertEquals("999", compactCount("999"))
        assertEquals("1K", compactCount("1000"))
        assertEquals("1${sep}2K", compactCount("1299"))
        assertEquals("100K", compactCount("100456"))
        assertEquals("999K", compactCount("999999"))
        assertEquals("2${sep}3M", compactCount("2345678"))
        assertEquals("1${sep}5B", compactCount("1500000000"))
        assertEquals("1.2K", compactCount("1.2K"))
    }
}
