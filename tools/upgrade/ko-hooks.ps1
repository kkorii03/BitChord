# Korean-fork hook bookkeeping for upstream upgrades (see docs/ko-fork-layout.md).
# Usage (from the repo root):
#   ko-hooks.ps1 list  [-Upstream v1.9]   -> rewrites docs/ko-hooks.md: every `// [KO]` line in upstream files
#   ko-hooks.ps1 diff  -Old <commit>      -> `// [KO]` lines present in <commit> but missing now (re-insert after a merge)
#   ko-hooks.ps1 mixed [-Upstream v1.9]   -> per upstream file, how many lines our fork still adds inside it
#                                            (the number to shrink: our code should live under ko/ instead)
param(
    [Parameter(Mandatory, Position = 0)][ValidateSet('list', 'diff', 'mixed')][string]$Mode,
    [string]$Upstream = 'v1.9',
    [string]$Old
)
$ErrorActionPreference = 'Stop'

function Get-KoLines([string]$rev) {
    # `git grep` prints rev:path:line:text; drop the rev prefix.
    $out = if ($rev) { git grep -n -F '[KO]' $rev -- '*.kt' '*.kts' '*.xml' } else { git grep -n -F '[KO]' -- '*.kt' '*.kts' '*.xml' }
    foreach ($l in $out) {
        if ($rev) { $l = $l.Substring($rev.Length + 1) }
        $p = $l.Split(':', 3)
        [pscustomobject]@{ Path = $p[0]; Line = [int]$p[1]; Text = $p[2].Trim() }
    }
}

$upstreamPaths = @{}
foreach ($p in git ls-tree -r --name-only $Upstream) { $upstreamPaths[$p] = 1 }
function Test-InUpstream([string]$path) { $upstreamPaths.ContainsKey($path) }

switch ($Mode) {
    'list' {
        $rows = Get-KoLines '' | Where-Object { Test-InUpstream $_.Path }
        $md = @("# [KO] hooks in upstream files (generated by tools/upgrade/ko-hooks.ps1 list, upstream $Upstream)", '',
            "Total: $($rows.Count) lines in $(@($rows | Select-Object -ExpandProperty Path -Unique).Count) files.", '',
            '| file:line | code |', '|---|---|')
        foreach ($r in $rows) { $md += "| $($r.Path):$($r.Line) | ``$($r.Text.Replace('|', '\|'))`` |" }
        $md | Out-File -Encoding utf8 docs/ko-hooks.md
        "docs/ko-hooks.md: $($rows.Count) hook lines"
    }
    'diff' {
        if (-not $Old) { throw '-Old <commit> is required' }
        $now = @{}
        foreach ($r in Get-KoLines '') { $now["$($r.Path)`t$($r.Text)"] = 1 }
        $missing = Get-KoLines $Old | Where-Object { -not $now.ContainsKey("$($_.Path)`t$($_.Text)") }
        foreach ($m in $missing) { "$($m.Path):$($m.Line)  $($m.Text)" }
        "missing: $(@($missing).Count)"
    }
    'mixed' {
        $total = 0
        foreach ($s in git diff --numstat $Upstream HEAD -- '*.kt') {
            $a, $d, $path = $s -split "`t"
            if ($a -eq '-' -or -not (Test-InUpstream $path)) { continue }
            $total += [int]$a
            [pscustomobject]@{ Added = [int]$a; Path = $path }
        }
        "total fork lines inside upstream .kt files: $total"
    }
}
